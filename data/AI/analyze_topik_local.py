def 방문자읽기():
    """방문자 원장을 기초지자체 단위로 정리하고 백분위를 다시 계산한다.

    ⚠️ 원장 264행에는 시(41110 수원시)와 그 일반구(41111~41117)가 함께 들어 있다.
       일반구는 기초지자체가 아니므로 시로 합쳐야 하고, 합치지 않으면 같은 방문을
       두 번 세는 데다 시 쪽 관광자원이 0건으로 잡힌다.
    """
    _raw = json.load(io.open(os.path.join(OUT, "analyze_visitor_gap.json"), encoding="utf-8"))
    src = {str(r["code"]): r for r in (_raw["데이터"] if isinstance(_raw, dict) else _raw)}

    합침 = []
    def 목적지(code):
        if code in 방문자병합:                 # 인천 동구 → 제물포구(중구)
            return 방문자병합[code]
        if code[-1] != "0" and code[:4] + "0" in src:   # 일반구 → 시
            return code[:4] + "0"
        return code

    tot = {}
    for code, r in src.items():
        d = 목적지(code)
        if d != code:
            합침.append((code, r["nm"], d))
        t = tot.setdefault(d, {"nm": src[d]["nm"] if d in src else r["nm"], "b": 0.0, "c": 0.0})
        t["b"] += float(r["b"]); t["c"] += float(r["c"])

    def pctr(vals):
        v = sorted(vals)
        return lambda x: bisect.bisect_left(v, x) / max(len(v) - 1, 1) * 100

    for t in tot.values():
        t["share"] = t["c"] / (t["b"] + t["c"]) * 100 if (t["b"] + t["c"]) else 0.0
    fb, fs = pctr([t["b"] for t in tot.values()]), pctr([t["share"] for t in tot.values()])
    for t in tot.values():
        t["pb"], t["ps"] = fb(t["b"]), fs(t["share"])
        t["gap"] = t["pb"] - t["ps"]
    return tot, 합침


